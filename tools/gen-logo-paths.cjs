// One-time build tool (Node-only; fontkit never ships in the app bundle).
// Shapes the Arabic word نَبَأ with real HarfHuzz-grade shaping (via fontkit)
// against the app's own Scheherazade New Bold font, extracts each glyph's
// vector outline, and emits a ready-to-import TS module of SVG path data —
// ordered for a calligrapher's natural right-to-left pen sequence.
const fontkit = require('fontkit');
const path = require('path');
const fs = require('fs');

const FONT_PATH = path.resolve(
  __dirname,
  '../frontend/node_modules/@expo-google-fonts/scheherazade-new/700Bold/ScheherazadeNew_700Bold.ttf',
);
const TEXT = 'نَبَأ'; // ن َ ب َ أ  (Naba)
const OUT_PATH = path.resolve(__dirname, '../frontend/src/logo/nabaPaths.ts');

const font = fontkit.openSync(FONT_PATH);
const run = font.layout(TEXT);
const upm = font.unitsPerEm; // font-space units per em (Y-up, origin at baseline)

// fontkit/HarfBuzz returns RTL glyph runs in final VISUAL left-to-right order,
// so glyphs[0] is the leftmost thing on screen; the LAST logical letter of the
// word ends up leftmost. Accumulate X by advance to place each glyph.
let cumX = 0;
const placed = run.glyphs.map((g, i) => {
  const pos = run.positions[i];
  const svg = g.path.toSVG(); // in font units, Y-up
  const x = cumX + pos.xOffset;
  const y = pos.yOffset;
  cumX += pos.xAdvance;
  return { name: g.name, svg, x, y, bbox: g.bbox };
});

// Identify each glyph by name (deterministic for this exact input string).
const byName = (n) => placed.find((p) => p.name === n);
const noonInit = byName('uni0646.init');
const kashida = byName('absAutoKashida');
const baMedi = byName('uni0628.medi');
const alifFina = byName('uni0627.fina');
const hamza = byName('uni0654');
const fathas = placed.filter((p) => p.name === 'uni064E');
// The two fatha marks share a glyph name; distinguish by X position (the one
// nearer noonInit's x is noon's fatha, the other is ba's).
const fathaNoon = fathas.reduce((a, b) => (Math.abs(a.x - noonInit.x) < Math.abs(b.x - noonInit.x) ? a : b));
const fathaBa = fathas.find((f) => f !== fathaNoon);

if (!noonInit || !kashida || !baMedi || !alifFina || !hamza || fathas.length !== 2) {
  throw new Error('Unexpected glyph shaping result — font or text changed; re-check gen-logo-paths.mjs');
}

// Convert a font-space (Y-up) glyph into an SVG <path> transform string that
// flips Y and places it at its shaped position, in a Y-down SVG coordinate
// space with the baseline at y=0.
function toSvgGroup({ svg, x, y }) {
  return { d: svg, transform: `translate(${round(x)} ${round(-y)}) scale(1 -1)` };
}
function round(n) {
  return Math.round(n * 100) / 100;
}

// Overall bounding box (font-space, Y-up) → used for the viewBox.
function unionBBox(glyphs) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const g of glyphs) {
    if (!g.bbox) continue;
    const gminX = g.x + g.bbox.minX;
    const gmaxX = g.x + g.bbox.maxX;
    const gminY = g.y + g.bbox.minY;
    const gmaxY = g.y + g.bbox.maxY;
    minX = Math.min(minX, gminX);
    maxX = Math.max(maxX, gmaxX);
    minY = Math.min(minY, gminY);
    maxY = Math.max(maxY, gmaxY);
  }
  return { minX, minY, maxX, maxY };
}
const bbox = unionBBox(placed);
// Y-down viewBox: top = -maxY (highest point, e.g. hamza+fatha), height spans to -minY.
const pad = upm * 0.08;
const viewBox = {
  x: round(bbox.minX - pad),
  y: round(-bbox.maxY - pad),
  width: round(bbox.maxX - bbox.minX + pad * 2),
  height: round(bbox.maxY - bbox.minY + pad * 2),
};

// Drawing order = a calligrapher's natural right-to-left pen sequence:
// ن (initial) → connector → ب (medial) → أ (final). Marks (hamza, harakat)
// are separated out so the animation can reveal the skeleton first, then the
// marks — matching real Arabic handwriting convention.
const basePaths = [noonInit, kashida, baMedi, alifFina].map(toSvgGroup);
const hamzaPath = toSvgGroup(hamza);
// Harakat in writing order: noon's fatha first (it was written first), then ba's.
const harakatPaths = [fathaNoon, fathaBa].map(toSvgGroup);

const file = `// AUTO-GENERATED by tools/gen-logo-paths.mjs — do not hand-edit.
// Source: Scheherazade New Bold, shaped via fontkit for نَبَأ (Naba).
// Regenerate with: node tools/gen-logo-paths.mjs

export type LogoGlyph = { d: string; transform: string };

// Drawing order: ن (initial) → kashida connector → ب (medial) → أ (final).
export const basePaths: LogoGlyph[] = ${JSON.stringify(basePaths, null, 2)};

// Hamza mark (sits above the alif).
export const hamzaPath: LogoGlyph = ${JSON.stringify(hamzaPath, null, 2)};

// The two fatha marks, in the order they were written (noon's, then ba's).
export const harakatPaths: LogoGlyph[] = ${JSON.stringify(harakatPaths, null, 2)};

// SVG viewBox that frames the whole word with a small margin, Y-down.
export const viewBox = ${JSON.stringify(viewBox, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, file);
console.log('Wrote', OUT_PATH);
console.log('viewBox:', viewBox);
console.log('basePaths:', basePaths.length, '| hamza: 1 | harakat:', harakatPaths.length);
